def decode_mime(value):
    if not value:
        return ''
    try:
        return str(make_header(decode_header(str(value))))
    except Exception:
        return str(value)

def message_text(msg):
    if msg.get_content_disposition()=='attachment':
        return ''
    if msg.is_multipart():
        children=msg.get_payload()
        if not isinstance(children,list):
            children=[]
        if msg.get_content_subtype().lower()=='alternative':
            # The alternatives are equivalent representations. Prefer plain
            # text so the same message is not indexed once as text and again
            # as HTML.
            for wanted in ('text/plain','text/html'):
                for part in children:
                    if part.get_content_type()==wanted and part.get_content_disposition()!='attachment':
                        text=message_text(part)
                        if text.strip(): return text
            return next((text for part in children if (text:=message_text(part)).strip()),'')
        return '\n'.join(text for part in children if (text:=message_text(part)).strip())
    if msg.get_content_type() not in ('text/plain','text/html'):
        return ''
    try:
        payload=msg.get_payload(decode=True)
        charset=msg.get_content_charset() or 'utf-8'
        text=payload.decode(charset,errors='replace') if isinstance(payload,(bytes,bytearray)) else str(payload or '')
    except Exception:
        text=str(msg.get_payload() or '')
    if msg.get_content_type()=='text/html':
        hp=Parser(); hp.feed(text); text='\n'.join(hp.text)
    return text

def normalize_subject(subject):
    subject=decode_mime(subject).strip()
    old=None
    while subject!=old:
        old=subject
        subject=re.sub(r'^\s*((re|fw|fwd)\s*:\s*)+','',subject,flags=re.I)
        subject=re.sub(r'^\s*\[[^\]]+\]\s*','',subject)
    return re.sub(r'\s+',' ',subject).strip() or '(no subject)'

def strip_quoted(text):
    lines=[]
    for line in text.splitlines():
        if re.match(r'^\s*>',line):
            continue
        if re.match(r'^\s*On .+ wrote:\s*$',line,re.I):
            break
        lines.append(line)
    return '\n'.join(lines)

def strip_signature(text):
    lines=text.splitlines()
    for i,line in enumerate(lines):
        if line.strip()=='--':
            return '\n'.join(lines[:i])
    return text

def strip_groups_footer(text):
    patterns=[r'^_+\s*$',r'^Groups\.io Links:',r'^You receive all messages sent to this group\.',r'^View/Reply Online']
    lines=[]
    for line in text.splitlines():
        if any(re.search(p,line,re.I) for p in patterns):
            break
        lines.append(line)
    return '\n'.join(lines)

def clean_message_body(text,opts):
    text=text.replace('\r\n','\n').replace('\r','\n')
    if opts.get('strip_quoted_replies',True): text=strip_quoted(text)
    if opts.get('strip_signatures',True): text=strip_signature(text)
    if opts.get('strip_groups_footer',True): text=strip_groups_footer(text)
    text='\n'.join(line.rstrip() for line in text.splitlines())
    text=re.sub(r'\n{3,}','\n\n',text).strip()
    return text

def parse_date(value):
    try:
        d=parsedate_to_datetime(value)
        if d.tzinfo is None: d=d.replace(tzinfo=timezone.utc)
        return d.astimezone(timezone.utc).isoformat()
    except Exception:
        return ''

