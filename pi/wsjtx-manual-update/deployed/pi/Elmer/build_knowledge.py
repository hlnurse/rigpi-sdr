def extract_docx_text(path):
    parts=[]
    with zipfile.ZipFile(path) as archive:
        names=['word/document.xml']+sorted(n for n in archive.namelist() if re.match(r'word/(header|footer)\d+\.xml$',n))
        for name in names:
            if name not in archive.namelist(): continue
            raw=archive.read(name).decode('utf-8',errors='replace')
            raw=re.sub(r'</w:(p|tr)>','\n',raw)
            text=html.unescape(re.sub(r'<[^>]+>',' ',raw))
            parts.append(text)
    return '\n'.join(parts)

def extract_rtf_text(path):
    raw=path.read_bytes().decode('latin-1',errors='replace')
    raw=re.sub(r"\\'[0-9a-fA-F]{2}",lambda m:bytes([int(m.group()[2:],16)]).decode('cp1252',errors='replace'),raw)
    raw=re.sub(r'\\(par|line)\b\s*','\n',raw)
    raw=re.sub(r'\\[a-zA-Z]+-?\d*\s?',' ',raw)
    raw=re.sub(r'\\[^a-zA-Z]',' ',raw)
    return raw.replace('{',' ').replace('}',' ')

def extract_groups_file_text(path):
    ext=path.suffix.lower()
    if ext=='.pdf':
        try:
            result=subprocess.run(['pdftotext','-layout',str(path),'-'],capture_output=True,timeout=120)
        except (FileNotFoundError,subprocess.TimeoutExpired):
            return ''
        return result.stdout.decode('utf-8',errors='replace') if result.returncode==0 else ''
    if ext=='.docx':
        try: return extract_docx_text(path)
        except (OSError,KeyError,zipfile.BadZipFile): return ''
    if ext=='.rtf': return extract_rtf_text(path)
    data=path.read_bytes()
    if b'\x00' in data: return ''
    return data.decode('utf-8',errors='replace')

def normalize_extracted_text(text):
    text=text.replace('\r\n','\n').replace('\r','\n')
    text='\n'.join(re.sub(r'[ \t]+',' ',line).strip() for line in text.splitlines())
    return re.sub(r'\n{3,}','\n\n',text).strip()

def import_groups_files(path,source_cfg):
    path=Path(path)
    if path.is_file() and zipfile.is_zipfile(path):
        with tempfile.TemporaryDirectory(prefix='elmer-groups-files-') as td:
            with zipfile.ZipFile(path) as archive: archive.extractall(td)
