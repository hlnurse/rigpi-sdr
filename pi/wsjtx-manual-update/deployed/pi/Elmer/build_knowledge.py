def is_archive_artifact(path):
    """Return true for platform metadata that is not knowledge content."""
    return any(part=='__MACOSX' or part=='.DS_Store' or part.startswith('._') for part in Path(path).parts)
def matches(value, patterns): return next((p for p in patterns if fnmatch.fnmatch(value,p)), None)
