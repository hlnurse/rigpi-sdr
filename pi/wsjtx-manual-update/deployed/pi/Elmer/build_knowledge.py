class Parser(HTMLParser):
    SKIP_TAGS={'script','style','noscript','template'}

    def __init__(self):
        super().__init__(); self.text=[]; self.links=[]; self.images=[]; self.image_details=[]; self.title=[]; self._in_title=False; self._skip_depth=0; self.ids=set(); self.keywords=[]
    def handle_starttag(self, tag, attrs):
        tag=tag.lower()
        if tag in self.SKIP_TAGS:
            self._skip_depth+=1
            return
        if self._skip_depth:
            return
        a=dict(attrs)
        if tag=='title': self._in_title=True
        if tag=='a' and a.get('href'): self.links.append(a['href'])
        if tag=='img' and a.get('src'):
            self.images.append(a['src'])
            self.image_details.append({
                'src':a['src'],'alt':a.get('alt',''),'title':a.get('title',''),
                'width':a.get('width',''),'height':a.get('height',''),
            })
        if a.get('id'): self.ids.add(a['id'])
        if a.get('name'): self.ids.add(a['name'])
        if tag=='meta' and a.get('name','').lower()=='keywords': self.keywords += [x.strip() for x in a.get('content','').split(',') if x.strip()]
    def handle_endtag(self, tag):
        tag=tag.lower()
        if tag in self.SKIP_TAGS:
            self._skip_depth=max(0,self._skip_depth-1)
            return
        if self._skip_depth:
            return
        if tag=='title': self._in_title=False
    def handle_data(self, data):
        if self._skip_depth:
            return
        s=' '.join(data.split())
        if s:
            self.text.append(s)
            if self._in_title: self.title.append(s)

def deep_merge(base, override):
    result=copy.deepcopy(base)
    for key,value in override.items():
        if isinstance(value,dict) and isinstance(result.get(key),dict):
            result[key]=deep_merge(result[key],value)
        else:
            result[key]=copy.deepcopy(value)
    return result

def load_json(path):
    with open(path,encoding='utf-8') as f:
        data=json.load(f)
    if not isinstance(data,dict):
        raise ValueError(f'Configuration file must contain a JSON object: {path}')
    return data

