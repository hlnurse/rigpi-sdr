def page_score(p, min_words):
    score=100
    if p['words']<min_words: score-=20
    if p['missing_images']: score-=25
    if p['broken_internal']: score-=25
    if p['legacy_hits']: score-=10
    if not p['title']: score-=10
    if not p['keywords']: score-=5
    return max(0,score)
