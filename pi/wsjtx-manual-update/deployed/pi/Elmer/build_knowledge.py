def analyze_knowledge(help_report, groups_reports, cfg):
    opts=cfg.get('analysis',{}).get('knowledge_analysis',{})
    if not opts.get('enabled',True):
        return {'enabled':False,'top_topics':[],'top_threads':[],'coverage_gaps':[],'recommendations':[],'promotion_candidates':[],'source_intelligence':[]}
    stop={str(x).casefold() for x in opts.get('stop_words',[])}
    min_len=int(opts.get('minimum_topic_length',3))
    token_re=re.compile(r"[A-Za-z0-9][A-Za-z0-9+._/-]*")
    forum=Counter(); help_counts=Counter(); examples=defaultdict(list); per_source=defaultdict(Counter)
    def tokens(text):
        for raw in token_re.findall(text or ''):
            t=raw.casefold().strip('._-/')
            if len(t)>=min_len and t not in stop and not t.isdigit():
                yield t
    for page in help_report.get('pages',[]):
        weighted=' '.join([page.get('title','')]*5 + page.get('keywords',[]) + [page.get('text','')])
        help_counts.update(set(tokens(weighted)))
    all_threads=[]
    source_intelligence=[]
    for gr in groups_reports or []:
        for t in gr.get('threads',[]):
            all_threads.append({'source_id':gr['source_id'],'thread_id':t['thread_id'],'subject':t['subject'],'message_count':t['message_count'],'authors':len(t.get('authors',[])),'first_date':t.get('first_date',''),'last_date':t.get('last_date','')})
        for m in gr.get('messages',[]):
            terms=set(tokens(m.get('thread_subject','')))
            forum.update(terms); per_source[gr['source_id']].update(terms)
            for term in terms:
                if len(examples[term])<3 and m.get('thread_subject','') not in examples[term]: examples[term].append(m.get('thread_subject',''))
        source_intelligence.append({'source_id':gr['source_id'],'name':gr.get('name',gr['source_id']),'authority':gr['authority'],'messages':gr['summary']['messages'],'threads':gr['summary']['threads'],'contributors':gr['summary']['contributors'],'date_start':gr['summary']['date_start'],'date_end':gr['summary']['date_end'],'tags':gr.get('tags',[])})
    top_topics=[]
    for term,count in forum.most_common(int(opts.get('top_topics',25))):
        top_topics.append({'topic':term,'forum_messages':count,'help_pages':help_counts.get(term,0),'examples':examples[term],'sources':{sid:c.get(term,0) for sid,c in per_source.items() if c.get(term,0)}})
    min_msgs=int(opts.get('gap_minimum_messages',5))
    gaps=[{'topic':term,'forum_messages':count,'help_pages':help_counts.get(term,0),'examples':examples[term],'sources':{sid:c.get(term,0) for sid,c in per_source.items() if c.get(term,0)}} for term,count in forum.items() if count>=min_msgs and help_counts.get(term,0)==0]
    gaps=sorted(gaps,key=lambda x:(-x['forum_messages'],x['topic']))[:int(opts.get('top_topics',25))]
    recs=[]
    max_count=max([x['forum_messages'] for x in gaps],default=1)
    for rank,x in enumerate(gaps,1):
        source_bonus=min(15,max(0,(len(x['sources'])-1)*8))
        confidence=min(99,round(45+45*x['forum_messages']/max_count+source_bonus))
        impact='Very High' if confidence>=90 else 'High' if confidence>=75 else 'Medium' if confidence>=60 else 'Review'
        recs.append({**x,'rank':rank,'confidence':confidence,'impact':impact,'recommendation':f"Create or expand a Help topic for {x['topic']}."})
    promotions=[x for x in recs if len(x['sources'])>=2 or x['confidence']>=80]
    top_threads=sorted(all_threads,key=lambda x:(-x['message_count'],x['subject'].casefold()))[:int(opts.get('top_threads',20))]
    return {'enabled':True,'top_topics':top_topics,'top_threads':top_threads,'coverage_gaps':gaps,'recommendations':recs,'promotion_candidates':promotions,'source_intelligence':source_intelligence,'topics_analyzed':len(forum)}

