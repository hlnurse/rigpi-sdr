    by_extension=dict(sorted(Counter(Path(d['path']).suffix.lower() or '(none)' for d in documents).items()))
    summary={'documents':len(documents),'duplicates':len(duplicates),'unsupported':unsupported,'extraction_failed_or_short':failed,'by_extension':by_extension}
